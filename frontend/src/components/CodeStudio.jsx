// Sanitizes streaming CSS to keep styles 100% syntactically valid and prevent style-dropping
function sanitizeStreamingCss(rawCss) {
  if (!rawCss) return "";
  let css = rawCss;

  // 1. Close unclosed comment if any
  const openComment = css.lastIndexOf("/*");
  const closeComment = css.lastIndexOf("*/");
  if (openComment > closeComment) {
    css += " */";
  }

  // 2. Count curly braces
  let openBraces = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") openBraces++;
    else if (css[i] === "}") openBraces--;
  }

  // 3. Balance unclosed braces and incomplete property values
  if (openBraces > 0) {
    const lastOpenParen = css.lastIndexOf("(");
    const lastCloseParen = css.lastIndexOf(")");
    if (lastOpenParen > lastCloseParen) {
      css += ")";
    }

    const trimmed = css.trimEnd();
    const lastChar = trimmed[trimmed.length - 1];
    if (lastChar && lastChar !== ";" && lastChar !== "{" && lastChar !== "}") {
      css += ";";
    }

    while (openBraces > 0) {
      css += "}";
      openBraces--;
    }
  }

  return css;
}

// Sanitizes streaming HTML to prevent rendering half-finished tags
function sanitizeStreamingHtml(rawHtml) {
  if (!rawHtml) return "";
  let clean = rawHtml.trim();

  // Remove trailing unclosed HTML comment <!-- ...
  clean = clean.replace(/<!--(?!.*-->).*$/, "");

  // If ends in an unclosed tag like '<div class="foo' or '<h1' or '<span style="'
  const lastOpen = clean.lastIndexOf("<");
  const lastClose = clean.lastIndexOf(">");
  if (lastOpen > lastClose) {
    clean = clean.slice(0, lastOpen);
  }

  return clean;
}

// Non-destructive DOM reconciliation between target and source
function syncAttributes(target, source) {
  const targetAttrs = target.attributes;
  const sourceAttrs = source.attributes;

  for (let i = targetAttrs.length - 1; i >= 0; i--) {
    const attrName = targetAttrs[i].name;
    if (!source.hasAttribute(attrName)) {
      target.removeAttribute(attrName);
    }
  }

  for (let i = 0; i < sourceAttrs.length; i++) {
    const attr = sourceAttrs[i];
    if (target.getAttribute(attr.name) !== attr.value) {
      target.setAttribute(attr.name, attr.value);
    }
  }
}

function morphChildren(targetParent, sourceParent) {
  let targetChild = targetParent.firstChild;
  let sourceChild = sourceParent.firstChild;

  while (sourceChild) {
    if (!targetChild) {
      targetParent.appendChild(sourceChild.cloneNode(true));
      sourceChild = sourceChild.nextSibling;
    } else if (
      targetChild.nodeType !== sourceChild.nodeType ||
      targetChild.nodeName !== sourceChild.nodeName
    ) {
      const nextTarget = targetChild.nextSibling;
      const clone = sourceChild.cloneNode(true);
      targetParent.replaceChild(clone, targetChild);
      targetChild = nextTarget;
      sourceChild = sourceChild.nextSibling;
    } else {
      morphNode(targetChild, sourceChild);
      targetChild = targetChild.nextSibling;
      sourceChild = sourceChild.nextSibling;
    }
  }

  while (targetChild) {
    const nextTarget = targetChild.nextSibling;
    targetParent.removeChild(targetChild);
    targetChild = nextTarget;
  }
}

function morphNode(target, source) {
  if (target.nodeType === Node.TEXT_NODE || target.nodeType === Node.COMMENT_NODE) {
    if (target.nodeValue !== source.nodeValue) {
      target.nodeValue = source.nodeValue;
    }
    return;
  }

  if (target.nodeType === Node.ELEMENT_NODE) {
    syncAttributes(target, source);
    morphChildren(target, source);
  }
}

